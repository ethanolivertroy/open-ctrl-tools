import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { cn } from "@/lib/utils"

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex h-full w-full flex-col overflow-hidden rounded-md bg-popover text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  children,
  open,
  onOpenChange,
  ...props
}: React.ComponentProps<typeof CommandPrimitive> & {
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  if (!open) return null

  return (
    <div className="fixed inset-0 z-50">
      {/* Backdrop */}
      <div
        className="fixed inset-0 bg-black/80"
        onClick={() => onOpenChange?.(false)}
      />
      {/* Dialog */}
      <div className="fixed inset-x-0 top-0 sm:left-1/2 sm:top-1/2 z-50 w-full sm:max-w-lg sm:-translate-x-1/2 sm:-translate-y-1/2 p-0 sm:p-4">
        <Command
          shouldFilter={false}
          className="rounded-lg border border-border bg-card shadow-lg [&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group-heading]]:text-muted-foreground [&_[cmdk-group]:not([hidden])_~[cmdk-group]]:pt-0 [&_[cmdk-input-wrapper]_svg]:h-5 [&_[cmdk-input-wrapper]_svg]:w-5 [&_[cmdk-input]]:h-12 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-3 [&_[cmdk-item]_svg]:h-5 [&_[cmdk-item]_svg]:w-5"
          {...props}
        >
          {children}
        </Command>
      </div>
    </div>
  )
}

function CommandInput({
  className,
  autoFocus = true,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Input> & { autoFocus?: boolean }) {
  const inputRef = React.useRef<HTMLInputElement>(null)

  React.useEffect(() => {
    if (autoFocus) {
      // Small delay to ensure DOM is ready after dialog animation
      const timer = setTimeout(() => {
        inputRef.current?.focus()
      }, 10)
      return () => clearTimeout(timer)
    }
  }, [autoFocus])

  return (
    <div className="flex items-center border-b border-border px-3">
      <SearchIcon className="mr-2 h-4 w-4 shrink-0 text-muted-foreground" />
      <CommandPrimitive.Input
        ref={inputRef}
        data-slot="command-input"
        autoFocus={autoFocus}
        className={cn(
          "flex h-11 w-full rounded-md bg-transparent py-3 text-sm outline-none placeholder:text-muted-foreground disabled:cursor-not-allowed disabled:opacity-50",
          className
        )}
        {...props}
      />
    </div>
  )
}

