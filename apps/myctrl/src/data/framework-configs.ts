/**
 * Get all available framework IDs
 */
export function getAllFrameworkIds(): string[] {
  return Object.keys(FRAMEWORK_CONFIGS);
}

/**
 * Get framework configuration by ID
 */
export function getFrameworkConfig(frameworkId: string): FrameworkConfig {
  const config = FRAMEWORK_CONFIGS[frameworkId];
  if (!config) {
    throw new Error(`Unknown framework: ${frameworkId}`);
  }
  return config;
}

/**
 * Check if a framework ID is valid
 */
export function isValidFramework(frameworkId: string): boolean {
  return frameworkId in FRAMEWORK_CONFIGS;
}

/**
 * Get all framework configs (type === 'framework')
 */
export function getFrameworks(): FrameworkConfig[] {
  return Object.values(FRAMEWORK_CONFIGS).filter(c => c.type === 'framework');
}

/**
 * Get all risk list configs (type === 'risk-list')
 */
export function getRiskLists(): FrameworkConfig[] {
  return Object.values(FRAMEWORK_CONFIGS).filter(c => c.type === 'risk-list');
}

/**
 * Get all configs with a specific tag
 */
export function getByTag(tag: string): FrameworkConfig[] {
  return Object.values(FRAMEWORK_CONFIGS).filter(c => c.tags?.includes(tag));
}

/**
 * Check if a config is a risk list
 */
export function isRiskList(frameworkId: string): boolean {
  const config = FRAMEWORK_CONFIGS[frameworkId];
  return config?.type === 'risk-list';
}

export function getBasePath(frameworkId: string): '/frameworks' | '/risk-lists' {
  return isRiskList(frameworkId) ? '/risk-lists' : '/frameworks';
}

/**
 * Get all configs with a specific license type
 */
export function getByLicense(license: LicenseType): FrameworkConfig[] {
  return Object.values(FRAMEWORK_CONFIGS).filter(c => c.license === license);
}
